#!/usr/bin/env python3
"""Index and check docs-1 documentation (standard library only, Python 3.9+).

usage: docs_index.py [--docs DIR] write          regenerate DIR/INDEX.md from the docs' frontmatter
       docs_index.py [--docs DIR] check          report errors (exit 1) and stale docs (warnings)
       docs_index.py [--docs DIR] covers PATH..  list the docs whose `covers` match these files
       docs_index.py [--docs DIR] next-id        print the next free DOC-n id
       docs_index.py [--docs DIR] verify ID..    stamp `verified: <today> <HEAD>` on docs you re-checked against the code
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

REQUIRED = ("id", "title", "summary", "type", "status", "updated")
TYPES = {"tutorial", "how-to", "reference", "explanation", "decision", "runbook"}
STATUSES = {"draft", "current", "deprecated", "superseded"}
HISTORY = {"deprecated", "superseded"}
SKIP = {"INDEX.md"}   # generated; area indexes are INDEX.md or INDEX-<area>.md
SPLIT_AT = 150        # past this many docs, each area gets its own INDEX.md and the main index lists areas


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    meta, key = {}, None
    for line in m.group(1).splitlines():
        if re.match(r"\s+-\s", line) and key:                       # block list item
            meta.setdefault(key, [])
            if isinstance(meta[key], list):
                meta[key].append(line.split("-", 1)[1].strip().strip("\"'"))
            continue
        kv = re.match(r"([A-Za-z_][\w-]*):\s*(.*)$", line)
        if not kv:
            continue
        key, val = kv.group(1), re.sub(r"\s+#.*$", "", kv.group(2)).strip()
        if val.startswith("[") and val.endswith("]"):
            val = [v.strip().strip("\"'") for v in val[1:-1].split(",") if v.strip()]
        elif val == "":
            val = [] if key in ("covers", "related") else ""
        else:
            val = val.strip("\"'")
        meta[key] = val
    return meta


PRUNE = {"node_modules", "vendor", "dist", "build", "target", "venv", "__pycache__", "site-packages"}


def repo_root(docs):
    top = git(docs, "rev-parse", "--show-toplevel")
    return Path(top) if top else docs.resolve().parent


def load(docs):
    """Every Markdown file under docs/, plus files anywhere in the repo whose frontmatter has a docs-1 id."""
    root, docs_abs, out = repo_root(docs), docs.resolve(), []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d not in PRUNE)
        for name in sorted(filenames):
            path = Path(dirpath) / name
            if not name.endswith(".md") or name in SKIP or re.fullmatch(r"INDEX-.*\.md", name):
                continue
            meta = frontmatter(path.read_text(encoding="utf-8", errors="replace"))
            inside = path.resolve().is_relative_to(docs_abs)
            if inside or (meta and re.fullmatch(r"DOC-\d+", str(meta.get("id", "")))):
                out.append((path.resolve(), meta))
    return out


def area(docs, path):
    docs_abs = docs.resolve()
    if path.is_relative_to(docs_abs):
        rel = path.relative_to(docs_abs)
        return "archive" if rel.parts[0] == "archive" else (rel.parts[0] if len(rel.parts) > 1 else "")
    rel = path.relative_to(repo_root(docs).resolve())
    return rel.parts[0] if len(rel.parts) > 1 else "(repo root)"


def shown(docs, path):
    return os.path.relpath(path, repo_root(docs).resolve())


def line(docs, base, path, m):
    link = Path(os.path.relpath(path, base.resolve())).as_posix()
    flag = "" if m.get("status") == "current" else f" ({m.get('status')})"
    return f"- {m.get('id')} [{m.get('title')}]({link}) {m.get('type')}{flag}: {m.get('summary')}"


def write(docs):
    items = [(p, m) for p, m in load(docs) if m and m.get("id")]
    groups = {}
    for p, m in items:
        key = "archive" if m.get("status") in HISTORY else area(docs, p)
        groups.setdefault(key, []).append((p, m))
    head = ["# Docs index", "",
            "Generated by docs_index.py from each doc's frontmatter; do not edit by hand. Code at HEAD wins over a doc;",
            "run `docs_index.py check` to list docs whose covered code changed after they were verified.", ""]
    body = []
    split = len(items) > SPLIT_AT
    for key in sorted(groups, key=lambda k: (k == "archive", k != "", k)):
        title = {"": "General", "archive": "History (deprecated, superseded)"}.get(key, key)
        rows = sorted(groups[key], key=lambda pm: pm[1].get("id"))
        if split and key not in ("", "archive"):
            sub = (docs / key if (docs / key).is_dir() else docs) / ("INDEX.md" if (docs / key).is_dir() else f"INDEX-{key}.md")
            sub.write_text("\n".join([f"# {key} docs", "", *(line(docs, sub.parent, p, m) for p, m in rows)]) + "\n")
            body += [f"- [{key}]({sub.relative_to(docs).as_posix()}): {len(rows)} docs"]
            continue
        body += [f"## {title}", *(line(docs, docs, p, m) for p, m in rows), ""]
    if split:
        body = ["## Areas"] + [b for b in body if b.startswith("- [")] + [""] + [b for b in body if not b.startswith("- [")]
    (docs / "INDEX.md").write_text("\n".join(head + body).rstrip() + "\n")
    print(f"wrote {docs / 'INDEX.md'}: {len(items)} docs")


def glob_re(pattern):
    pattern = pattern.strip().lstrip("./")
    if pattern.endswith("/"):
        pattern += "**"
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        elif pattern[i] == "?":
            out, i = out + "[^/]", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile(out + "(?:/.*)?$")


def git(root, *args):
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def stale(root, m):
    """Commits touching the doc's covered paths since it was verified (None if unknown)."""
    covers, verified = m.get("covers") or [], (m.get("verified") or "").split()
    if not covers or not verified:
        return None
    spec = [f":(glob){c.rstrip('/') + '/**' if c.endswith('/') else c}" for c in covers]
    since = [f"{verified[1]}..HEAD"] if len(verified) > 1 and git(root, "cat-file", "-e", verified[1]) is not None \
        else [f"--since={verified[0]}T00:00:00"]     # no usable commit: by date, same-day changes included
    out = git(root, "log", "--format=%h", *since, "--", *spec)
    return None if out is None else [c for c in out.splitlines() if c]


def check(docs):
    root = repo_root(docs)
    errors, warnings, ids = [], [], {}
    items = load(docs)
    for p, m in items:
        rel = shown(docs, p)
        if not m or not m.get("id"):
            warnings.append(f"{rel}: no docs-1 frontmatter, not indexed")
            continue
        for k in REQUIRED:
            if not m.get(k):
                errors.append(f"{rel}: missing {k}")
        if m.get("id"):
            if not re.fullmatch(r"DOC-\d+", m["id"]):
                errors.append(f"{rel}: id {m['id']} is not DOC-<number>")
            ids.setdefault(m["id"], []).append(rel)
        if m.get("type") and m["type"] not in TYPES:
            errors.append(f"{rel}: type {m['type']} not in {sorted(TYPES)}")
        if m.get("status") and m["status"] not in STATUSES:
            errors.append(f"{rel}: status {m['status']} not in {sorted(STATUSES)}")
        if m.get("status") == "superseded" and not m.get("superseded_by"):
            errors.append(f"{rel}: superseded but no superseded_by")
        if m.get("status") in HISTORY and area(docs, p) != "archive":
            warnings.append(f"{rel}: {m['status']} doc outside docs/archive/")
        for target in re.findall(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", p.read_text(encoding="utf-8", errors="replace")):
            if re.match(r"[a-z]+:", target):
                continue
            dest = (root / target.lstrip("/")) if target.startswith("/") else (p.parent / target)
            if not dest.exists():
                errors.append(f"{rel}: broken link {target}")
        commits = stale(root, m) if m.get("status") == "current" else None
        if commits:
            warnings.append(f"{rel}: {len(commits)} commit(s) touched its covered paths since verified "
                            f"({m.get('verified')}), latest {commits[0]}; re-check it")
        elif m.get("status") == "current" and m.get("covers") and not m.get("verified"):
            warnings.append(f"{rel}: never verified against the code")
    known = set(ids)
    for p, m in items:
        for k in ("related", "supersedes", "superseded_by"):
            for ref in ([m.get(k)] if isinstance(m.get(k), str) else m.get(k) or []) if m else []:
                if ref and ref not in known:
                    errors.append(f"{shown(docs, p)}: {k} {ref} is not a known id")
    for i, files in ids.items():
        if len(files) > 1:
            errors.append(f"duplicate id {i}: {', '.join(files)}")
    index = docs / "INDEX.md"
    if not index.exists():
        errors.append("INDEX.md missing: run docs_index.py write")
    else:
        listed = set(re.findall(r"^- (DOC-\d+) ", index.read_text(), re.M))
        for sub in list(docs.glob("*/INDEX.md")) + list(docs.glob("INDEX-*.md")):
            listed |= set(re.findall(r"^- (DOC-\d+) ", sub.read_text(), re.M))
        if listed != known:
            errors.append("INDEX.md is out of date: run docs_index.py write")
    for e in errors:
        print("ERROR", e)
    for w in warnings:
        print("STALE?" if "commit(s)" in w else "WARN", w)
    print(f"{len(items)} docs, {len(errors)} errors, {len(warnings)} warnings")
    return 1 if errors else 0


def covers(docs, paths):
    root = repo_root(docs).resolve()
    rels = []
    for raw in paths:
        p = Path(raw).resolve()
        rels.append(p.relative_to(root).as_posix() if p.is_relative_to(root) else raw.lstrip("./"))
    for p, m in load(docs):
        if not m:
            continue
        pats = [glob_re(c) for c in m.get("covers") or []]
        if any(pt.match(r) for r in rels for pt in pats):
            print(f"{m.get('id')} {shown(docs, p)} [{m.get('status')}]: {m.get('summary')}")


def next_id(docs):
    nums = [int(m["id"][4:]) for _, m in load(docs) if m and re.fullmatch(r"DOC-\d+", m.get("id") or "")]
    print(f"DOC-{max(nums, default=0) + 1:03d}")


def verify(docs, ids):
    import datetime
    stamp = f"{datetime.date.today().isoformat()} {git(docs, 'rev-parse', '--short', 'HEAD') or ''}".strip()
    found = set()
    for p, m in load(docs):
        if not m or m.get("id") not in ids:
            continue
        text = p.read_text(encoding="utf-8")
        head, sep, body = text[4:].partition("\n---\n")
        if re.search(r"(?m)^verified:.*$", head):
            head = re.sub(r"(?m)^verified:.*$", f"verified: {stamp}", head, count=1)
        else:
            head += f"\nverified: {stamp}"
        p.write_text("---\n" + head + sep + body, encoding="utf-8")
        found.add(m["id"])
        print(f"{m['id']} {shown(docs, p)}: verified {stamp}")
    for i in sorted(set(ids) - found):
        print(f"{i}: no such doc")
    return 0 if found == set(ids) else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--docs", default="docs", help="docs folder (default: docs)")
    ap.add_argument("command", choices=["write", "check", "covers", "next-id", "verify"])
    ap.add_argument("paths", nargs="*")
    a = ap.parse_args()
    docs = Path(a.docs)
    if not docs.is_dir():
        sys.exit(f"no docs folder at {docs}")
    if a.command == "write":
        write(docs)
    elif a.command == "check":
        sys.exit(check(docs))
    elif a.command == "verify":
        sys.exit(verify(docs, a.paths))
    elif a.command == "covers":
        covers(docs, a.paths)
    else:
        next_id(docs)


if __name__ == "__main__":
    main()
