#!/usr/bin/env python3
"""Generate mod/codmod/codmod_tuning.cfg from the bg_codCvars[] table in bg_cod.c.

Writes one `set` line per non-archived cod_* cvar (flags without CVAR_ARCHIVE), plus
`set cod_enable "1"`. Values that mod/codmod/codmod.cfg already sets with set/seta override the
table default (codmod.cfg is exec'd later, so its value is the effective one) and get a
trailing comment. Run once from the pre-split defaults; afterwards the cfg is the source of truth.

Usage: scripts/gen-cod-tuning.py [bg_cod.c] [codmod.cfg] [out.cfg]
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "iortcw/SP/code/game/bg_cod.c"
modcfg = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "mod/codmod/codmod.cfg"
out = Path(sys.argv[3]) if len(sys.argv) > 3 else root / "mod/codmod/codmod_tuning.cfg"

text = src.read_text()
m = re.search(r"bg_codCvars\[\]\s*=\s*\{(.*?)\n\};", text, re.S)
if not m:
    sys.exit("bg_codCvars[] table not found")
body = "\n".join(re.sub(r"//.*", "", ln) for ln in m.group(1).splitlines())

entry = re.compile(r'\{\s*"(cod_\w+)"\s*,\s*"([^"]*)"\s*,\s*([^,]+?)\s*,')
table = {}  # name -> (default, flags); later duplicates win, order of first appearance kept
for name, default, flags in entry.findall(body):
    table[name] = (default, flags)

overrides = {}
setre = re.compile(r'^\s*seta?\s+(cod_\w+)\s+"?([^"\s/]*)"?', re.I)
if modcfg.exists():
    for ln in modcfg.read_text().splitlines():
        mm = setre.match(ln)
        if mm:
            overrides[mm.group(1)] = mm.group(2)

lines = [
    "// codmod_tuning.cfg -- generated by scripts/gen-cod-tuning.py from the pre-split bg_cod.c defaults;",
    "// codmod's source of truth for cod_* tuning; edit here, not in C.",
    "// Archived (user-facing) cod_* cvars are not listed: they belong in codmod_defaults.cfg.",
    "// Lines marked 'codmod.cfg override' took the value codmod.cfg set (effective before the split).",
    "",
    'set cod_enable "1"',
    "",
]
n = 0
for name, (default, flags) in table.items():
    if "CVAR_ARCHIVE" in flags or name == "cod_enable":
        continue
    val = default
    note = ""
    if name in overrides and overrides[name] != default:
        val = overrides[name]
        note = f' // codmod.cfg override (table default "{default}")'
    lines.append(f'set {name} "{val}"{note}')
    n += 1
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({n} cvars + cod_enable)")
