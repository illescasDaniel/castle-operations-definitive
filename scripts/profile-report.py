#!/usr/bin/env python3
"""Turn the engine's profiling CSVs (see profiling/README.md) of one scripts/profile.sh session into summary.md,
meta.json and the profiling/README.md format description. Reads <dir>/mode1/runN and <dir>/mode2/runN.
Run 1 of each mode is the warm-up; the other runs are the measured repeats (per-run values, median and range are reported).
Frame statistics use the bench window (frames.csv bench_window=1, the same stretch the FPS numbers cover); startup frames
are reported separately."""
import argparse, csv, datetime, json, platform, statistics, subprocess, time
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def sorted_runs(mode_dir: Path):
    return sorted((d for d in mode_dir.glob("run*") if d.is_dir()), key=lambda d: int(d.name[3:]))


def read_csv(p: Path):
    if not p.is_file():
        return []
    with p.open() as f:
        return list(csv.DictReader(f))


def fl(x, d=0.0):
    try:
        return float(x)
    except (TypeError, ValueError):
        return d


def pctl(v, q):
    v = sorted(v)
    return v[min(len(v) - 1, int(round((len(v) - 1) * q)))] if v else 0.0


def mean(v):
    v = list(v)
    return statistics.fmean(v) if v else 0.0


def med(v):
    v = list(v)
    return statistics.median(v) if v else 0.0


def rng(v):
    v = list(v)
    return (min(v), max(v)) if v else (0.0, 0.0)


def sh(cmd, cwd=ROOT):
    try:
        return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:
        return ""


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def mr(v, fmt="{:.3f}"):
    """median [min-max] of a list of per-run values"""
    v = list(v)
    if not v:
        return "-"
    lo, hi = rng(v)
    return f"{fmt.format(med(v))} [{fmt.format(lo)}-{fmt.format(hi)}]" if len(v) > 1 else fmt.format(v[0])


README = """# profiling/ - render profile data (generated by `scripts/profile.sh`, git-ignored)

One folder per session: `profiling/<stamp>-<label>/` (`profiling/latest` points at the newest). Start with `summary.md`.
The label names the condition (e.g. `framewarp-off`); `meta.json` and `environment/` record exactly what ran.

```
summary.md      ranked findings (human + agent entry point), median and range over the measured runs
meta.json       git SHAs, GPU/driver, resolution, cvars, command line, protocol, caveats
environment/    versions.txt, outer.diff / engine.diff (dirty trees), sha256.txt (binaries, modules, demo), packs.txt (names +
                sizes only), mod cfgs, nvidia-smi.txt
bench-modeN.log console output of the bench runs
mode1/runK/     r_gpuProfile 1: normal speed. Use for FPS, GPU pass times, CPU scopes, per-frame series
mode2/runK/     r_gpuProfile 2: adds per-batch timestamps => per-shader GPU/CPU cost. FPS NOT representative
                (the extra queries slow the frame); relative shader costs are still valid.
```
runK: run1 is a warm-up, the others are measured repeats. Each runK has:

* `passes.csv` - one row per GPU pass (a "mark" interval, see below). Columns: `avg_ms_per_frame` (over ALL 3D frames
  incl. startup, 0 when the pass did not run), `share_pct`, `avg_ms_when_run`, `p50/p95/p99/max_ms`, `hit_pct`. Mode 2 only:
  `batch_ms_per_frame` (time of draw batches ending in the pass), `non_batch_ms_per_frame` (pass minus batches: fullscreen
  work, clears, GPU idle gaps, timestamp overhead - not purely compute), `batches_per_frame`. The report recomputes
  per-pass means over the bench window from frames.csv; prefer those.
* `shaders.csv` (mode 2) - one row per (shader, pass, entity kind, stage iterator, depth_fill), sorted by GPU time.
  `gpu_ms_per_frame`, `gpu_pct_of_frame`, `gpu_us_per_batch`, `max_batch_us`, `cpu_ms_per_frame` (CPU time submitting those
  batches), `verts/tris_per_frame` (submitted, repeated cascades/passes count again), `draws_per_frame` = real
  glDrawElements / glMultiDrawElements submissions (also in depth passes), `subdraws_per_frame` counts each range of a
  multi-draw, `hit_pct`. `kind`: world, ent_mdv, ent_mds, ent_mdc, ent_brush, ent_other. `iterator`: Generic, Sky, other.
  `depth_fill` 1 = depth-only draw (prepass, shadow maps). A shader appears once per pass it ran in.
* `cpu_scopes.csv` - CPU time per frame (ms), SDL perf counter. Scopes are INCLUSIVE and nest, never sum them:
  `fe_RE_RenderScene` > `fe_R_RenderView` > `fe_*`; `be_RB_ExecuteRenderCommands` > `be_RB_DrawSurfs` >
  `be_RB_RenderDrawSurfList` > `assemble_<kind>_<color|depth>` (the rb_surfaceTable call that builds geometry; for VAO
  surfaces it contains the draw) and `be_RB_EndSurface_stage_iterator` (state + submit; contains `be_RB_UpdateTessVao`
  and `be_R_DrawElements`, which include driver time). MDS surface assembly is split into `mds_bones`, `mds_lod_index`
  (LOD + index/collapse build), `mds_skin` (vertex deform), `mds_tangent`, `mds_prevpos_depth` (SMAA velocity); `_color` /
  `_depth` = main passes vs depth-fill (prepass + shadow) passes. These are inside `assemble_ent_mds_*`.
  `be_GLimp_EndFrame` (swap) is charged to the following frame. `avg_us_per_call` = ms * 1000 / calls.
* `counters.csv` - per-frame event counts (MDS surfaces, emitted verts/tris, tangent verts, full-LOD surfaces), all frames
  and bench window.
* `cascades.csv` - sun shadow cascades: frames rendered / reused, why a cached cascade (1, 2) was re-rendered
  (`rerender_*`), GPU interval of the render, and in mode 2 batches/tris/verts/MDS share per render.
* `mds_lod_summary.csv`, `mds_lod.csv` (only if the build has the MDS LOD diagnostics) - MDS surfaces by view (`casc0-3`,
  `other_shadow`, `prepass`, `color`) and LOD decision reason (`proj_nonpos`, `flag_full`, `proj_clamped`, `computed_full`,
  `computed_reduced`) with emitted/max verts and tris over the whole run; and a sample (every 7th depth-view surface) with
  entity, surface, projected radius, LOD and the main color pass decision for the same surface (`main_*`, -1 = none seen).
* `cvars.csv` - values of the renderer/pacing cvars at the end of the run. `wolfconfig_after_run.cfg`, `bench_override.cfg`
  and `console.log.gz` are the run's complete settings and log; `gpu_telemetry.csv` = clocks/temperature/power every 250 ms.
* `frames.csv` - one row per 3D frame: `frame`, `ref_time_ms` (game time), `x,y,z,yaw,pitch` camera, `bench_window`
  (1 = inside the measurement window, `bench_frame` its index), `gpu_ms`, `batches/draws/subdraws/tris` (mode 2),
  `casc{0-3}_state/reason/ms` (0 unseen, 1 rendered, 2 reused; reason codes in the report; ms = GPU interval of that cascade's
  render), `cnt_*`, `cpu_*_ms` per scope, `pass_*_ms` per pass.
* `run.json` - engine-side facts: mode, frame counts, dropped frames, GL renderer, resolution, a few cvars.
* `bench_line.txt`, `bench_frametimes.txt` - the bench's own FPS summary and wall-clock frame times.

## Pass names (GPU mark intervals; a pass is the GPU time since the previous mark, including GPU idle gaps)
`frame_start` clears/setup, `shadowmap/sunshadow/flashshadow` shadow maps, `prepass` depth prepass, `depthcopy`,
`sunshadowmask/flashmask` shadow resolve, `ssao_*` GTAO chain, `scene_opaque` opaque colour pass, `scene` blended/rest
(`scene_noworld` for UI/viewmodel scenes), `sun/flares/rays_*` sun effects, `bloom_*`, `tm_*`/`tonemap_copy` tone mapping,
`smaa_*` SMAA (`smaa_t2x_resolve` = temporal resolve shader, `smaa_t2x_copy_scene` / `smaa_t2x_copy_history` = the two copies),
`grade` colour grade shader and `grade_copy` its copy back, `2d` HUD/menus, `warp_*`/`warp_present` frame-warp compositor,
`present_blit` final blit. Draw batches are attributed to the pass whose mark they end before.

## How to use
1. `summary.md` for the ranking. 2. `shaders.csv` grouped by shader for content/shader work. 3. `frames.csv` sorted by
`gpu_ms` for the worst scenes (join `x,y,z,yaw,pitch` with `scripts/shot-at.sh` / `known_spots`; replay the same `ref_time_ms`
window rather than teleporting). 4. Compare sessions with `scripts/profile-compare.py A B` (per-run values, medians, ranges);
for A/B tests of a change use `scripts/profile-ab.sh` (interleaved ABBA). Timings are GPU timestamp deltas: neighbouring
passes can blur by a few percent. Mode 2 costs must not be subtracted from mode 1 costs.
"""

CASC_REASON_NAMES = ["cache_invalid", "map_size_changed", "scheduled_refresh", "cache_too_old", "extent_changed",
                     "light_axes_changed", "box_moved_past_margin", "not_cached_level"]


def load_run(rd: Path):
    r = {"name": rd.name, "dir": rd}
    r["frames"] = read_csv(rd / "frames.csv")
    r["passes"] = read_csv(rd / "passes.csv")
    r["cpu"] = read_csv(rd / "cpu_scopes.csv")
    r["counters"] = read_csv(rd / "counters.csv")
    r["cascades"] = read_csv(rd / "cascades.csv")
    r["shaders"] = read_csv(rd / "shaders.csv")
    r["mdslod"] = read_csv(rd / "mds_lod_summary.csv")  # absent in sessions from before C3
    r["mdslod_samples"] = read_csv(rd / "mds_lod.csv")
    r["run"] = json.loads((rd / "run.json").read_text()) if (rd / "run.json").is_file() else {}
    line = (rd / "bench_line.txt").read_text().strip() if (rd / "bench_line.txt").is_file() else ""
    r["bench_line"] = line
    r["bench"] = {k: fl(v) for k, v in (t.split("=", 1) for t in line.split() if "=" in t)}
    fr = r["frames"]
    if fr and "bench_window" in fr[0]:
        r["win"] = [x for x in fr if x["bench_window"] == "1"]
        r["pre"] = [x for x in fr if x["bench_window"] != "1"]
        r["window_src"] = "bench_window"
    else:  # old captures: skip the first 60 frames
        r["win"] = [x for x in fr if int(x["frame"]) >= 60]
        r["pre"] = [x for x in fr if int(x["frame"]) < 60]
        r["window_src"] = "first 60 frames skipped"
    return r


# nvidia-smi clocks_event_reasons bits (NVML nvmlClocksEventReason*)
NVML_REASON_BITS = {0x1: "gpu idle", 0x2: "app clocks", 0x4: "sw power cap", 0x8: "hw slowdown", 0x10: "sync boost",
                    0x20: "sw thermal", 0x40: "hw thermal", 0x80: "hw power brake", 0x100: "display clock"}


def num(s):
    """nvidia-smi value with its unit ('1845 MHz', '49.00 W', '27 %') -> float, or None"""
    try:
        return float(str(s).replace("MHz", "").replace("W", "").replace("%", "").strip())
    except (TypeError, ValueError):
        return None


def reason_text(masks):
    """{'0x4': 3} (reason masks without bit 0x1, hex -> samples) -> '0x4 x3 (sw power cap)'; 'none' when empty"""
    if not masks:
        return "none"
    return "; ".join(f"{k} x{n} ({'+'.join(NVML_REASON_BITS.get(1 << i, f'bit{i}') for i in range(16) if int(k, 16) >> i & 1)})"
                     for k, n in masks.items())


def telemetry(rd: Path, bench_secs: float):
    """gpu_telemetry.csv of one run. Window columns use the bench window: the telemetry rows carry wall-clock timestamps,
    frames.csv does not, so the window is bench_line.txt's mtime (written when the bench ends) minus its `seconds=`.
    Accurate to about one 250 ms sample at each edge. Without bench_line.txt the window is not aligned and says so."""
    p = rd / "gpu_telemetry.csv"
    if not p.is_file():
        return None
    with p.open() as f:
        rr = csv.reader(f)
        hdr = [h.strip() for h in next(rr, [])]
        rows = [dict(zip(hdr, [v.strip() for v in r])) for r in rr if r]
    if not rows:
        return None

    def col(rs, prefix):
        c = next((h for h in hdr if h.startswith(prefix)), None)
        return [v for v in (num(r.get(c)) for r in rs) if v is not None] if c else []

    reason_col = next((h for h in hdr if "event_reasons" in h or "throttle" in h), None)

    def mask(r):
        try:
            return int(r.get(reason_col, ""), 0) if reason_col else None
        except ValueError:
            return None

    stamped = []
    for r in rows:
        try:
            stamped.append((datetime.datetime.strptime(r.get("timestamp", ""), "%Y/%m/%d %H:%M:%S.%f").timestamp(), r))
        except ValueError:
            pass
    bl = rd / "bench_line.txt"
    aligned, win, align = False, [], "NOT aligned (no bench_line.txt or no parseable timestamps): window columns are n/a"
    if stamped and bench_secs and bl.is_file():
        end = bl.stat().st_mtime
        gap = end - max(t for t, _ in stamped)  # measured: +0.28 s in every captured run; far more means mtimes were lost
        if -1.0 <= gap <= 5.0:
            aligned = True
            win = [r for t, r in stamped if end - bench_secs <= t <= end]
            align = f"aligned: window = bench_line.txt mtime - {bench_secs:g} s (+-1 sample at each edge)"
        else:
            align = "NOT aligned: bench_line.txt mtime is not near the last telemetry sample (file mtimes lost in a copy? use cp -a)"
    sm_w, masks = col(win, "clocks.current.sm"), [m for m in map(mask, win) if m is not None]
    other = Counter(m & ~0x1 for m in masks if m & ~0x1)
    sm_all, temp, pw = col(rows, "clocks.current.sm") or col(rows, "clocks.sm"), col(rows, "temperature"), col(rows, "power")
    return {"samples": len(rows), "aligned": aligned, "align": align, "window_samples": len(win),
            "sm_mhz_min_window": min(sm_w) if sm_w else None, "sm_mhz_mean_window": mean(sm_w) if sm_w else None,
            "sm_mhz_min_run": min(sm_all) if sm_all else 0, "temp_c_max": max(temp) if temp else 0,
            "power_w_mean": mean(pw), "idle_bit_samples_window": sum(1 for m in masks if m & 0x1), "masks_window": len(masks),
            "other_reason_bits_window": {f"0x{m:x}": n for m, n in sorted(other.items())}}


def frame_stats(rows):
    g = [fl(x["gpu_ms"]) for x in rows]
    if not g:
        return {"n": 0, "mean": 0, "p50": 0, "p95": 0, "p99": 0, "max": 0}
    return {"n": len(g), "mean": mean(g), "p50": pctl(g, .5), "p95": pctl(g, .95), "p99": pctl(g, .99), "max": max(g)}


def mds_lod_section(run):
    """'MDS LOD in depth views' tables from mds_lod_summary.csv (whole run) and mds_lod.csv (sampled, bench window)."""
    L = ["## MDS LOD in depth views (last measured mode 1 run)\n",
         "Surfaces by view and LOD decision reason. `proj_nonpos`: RB_ProjectRadius returned 0 (full-LOD fallback); `flag_full`: "
         "REFLAG_FULL_LOD; `proj_clamped`: projected radius >= 1; `computed_full`: radius < 1 but LOD value still 1.0; "
         "`computed_reduced`: LOD < 1. Verts/tris are emitted vs the surface maximum. Whole run (warm-up included).\n"]
    rows = []
    tot = {}
    for r in run["mdslod"]:
        tot[r["view"]] = tot.get(r["view"], 0.0) + fl(r["surfaces"])
    for r in run["mdslod"]:
        n = fl(r["surfaces"])
        if not n:
            continue
        mv, ev = fl(r["max_verts"]), fl(r["emitted_verts"])
        mt, et = fl(r["max_tris"]), fl(r["emitted_tris"])
        rows.append((r["view"], r["reason"], f"{n:.0f}", f"{100 * n / tot[r['view']]:.1f}%", f"{ev:.0f}", f"{mv:.0f}",
                     f"{100 * ev / mv:.1f}%" if mv else "-", f"{et:.0f}", f"{mt:.0f}", f"{100 * et / mt:.1f}%" if mt else "-"))
    L.append(table(rows, ["view", "reason", "surfaces", "share of view", "emitted verts", "max verts", "verts %", "emitted tris",
                          "max tris", "tris %"]))
    L.append("")
    smp = run.get("mdslod_samples") or []
    win = run.get("win") or []
    if smp and win:
        t0 = min(fl(x["ref_time_ms"]) for x in win)
        t1 = max(fl(x["ref_time_ms"]) for x in win)
        smp = [x for x in smp if t0 <= fl(x["ref_time_ms"]) <= t1]
    if smp:
        L.append(f"### Sampled depth-view surfaces vs the main color pass (bench window, {len(smp)} samples)\n")
        agg = {}
        for x in smp:
            a = agg.setdefault((x["view"], x["reason"]), [0, 0, 0, 0, 0, 0.0])
            a[0] += 1
            a[1] += fl(x["emitted_verts"])
            a[2] += fl(x["max_verts"])
            if fl(x["main_verts"], -1) >= 0:
                a[3] += 1
                a[4] += fl(x["main_verts"])
                a[5] += fl(x["emitted_verts"])
        rows = []
        for (v, rs), a in sorted(agg.items()):
            rows.append((v, rs, a[0], f"{100 * a[1] / a[2]:.1f}%" if a[2] else "-", a[3],
                         f"{100 * a[5] / a[4]:.1f}%" if a[4] else "-"))
        L.append(table(rows, ["view", "reason", "samples", "emitted/max verts", "with main ref", "emitted vs main-pass verts"]))
        L.append("\n`emitted vs main-pass verts` > 100% means the depth view drew more detail than the main view did for the same "
                 "surface (reference = latest main color decision for that entity/surface, usually the previous frame).\n")
    return L


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--label", default="")
    ap.add_argument("--args", default="")
    a = ap.parse_args()
    d = Path(a.dir)
    (d.parent / "README.md").write_text(README)

    m1 = [load_run(x) for x in sorted_runs(d / "mode1")]
    m2 = [load_run(x) for x in sorted_runs(d / "mode2")]
    meas1 = m1[1:] if len(m1) > 1 else m1
    meas2 = m2[1:] if len(m2) > 1 else m2
    last1 = meas1[-1] if meas1 else None
    last2 = meas2[-1] if meas2 else None
    run1 = last1["run"] if last1 else {}
    run2 = last2["run"] if last2 else {}
    tele = {}  # keyed by mode and run: mode2 runs share the run names of mode1
    for r in m1 + m2:
        t = telemetry(r["dir"], r["bench"].get("seconds", 0.0))
        if t:
            tele[f"{r['dir'].parent.name}/{r['name']}"] = t

    meta = {
        "created": time.strftime("%Y-%m-%d %H:%M:%S"), "label": a.label, "extra_bench_args": a.args,
        "git_outer": sh(["git", "rev-parse", "--short", "HEAD"]),
        "git_engine": sh(["git", "rev-parse", "--short", "HEAD"], ROOT / "iortcw"),
        "git_dirty": bool(sh(["git", "status", "--porcelain"]) or sh(["git", "status", "--porcelain"], ROOT / "iortcw")),
        "host": platform.node(), "kernel": platform.release(),
        "gpu_smi": sh(["nvidia-smi", "--query-gpu=name,driver_version,clocks.max.sm,power.limit", "--format=csv,noheader"]),
        "protocol": {"mode1_runs": len(m1), "mode1_measured": [r["name"] for r in meas1], "mode2_runs": len(m2),
                     "mode2_measured": [r["name"] for r in meas2], "warmup": "run1 of each mode",
                     "window": last1["window_src"] if last1 else ""},
        "environment_dir": "environment/",
        "gpu_telemetry": tele,
        "mode1_run": run1, "mode2_run": run2,
        "caveats": [
            "mode1 FPS/pass times are real; mode2 adds timestamp pairs per draw batch (~8% slower), so its absolute times are inflated "
            "and must not be subtracted from mode1",
            "GPU pass buckets are timestamp intervals since the previous mark: they include GPU idle gaps while the CPU submits work",
            "CPU scopes are inclusive and nested: never sum them; swap time is charged to the next frame",
            "headless gamescope run; resolution is the bench headless size, not necessarily the user's display",
            f"{len(meas1)} measured mode1 run(s): ranges describe run-to-run variation, not a confidence interval",
        ],
    }
    (d / "meta.json").write_text(json.dumps(meta, indent=1))

    L = []
    L.append(f"# Render profile: {a.label}\n")
    L.append(f"Session `{d.name}` - engine {meta['git_engine']}, outer {meta['git_outer']}{' (dirty tree, diffs in environment/)' if meta['git_dirty'] else ''}, "
             f"{run1.get('resolution', '?')} on {run1.get('gl_renderer', '?')}; r_frameWarp {run1.get('r_frameWarp', '?')}, "
             f"r_aa {run1.get('r_aa', '?')}, r_ao {run1.get('r_ao', '?')}. Extra bench args: `{a.args or 'none'}`.\n")
    L.append(f"Protocol: mode 1 = {len(m1)} runs (run1 warm-up, {len(meas1)} measured), mode 2 = {len(m2)} runs. Every figure below is "
             f"`median [min-max]` over the measured mode 1 runs unless marked otherwise. Frame statistics cover the bench window "
             f"({last1['window_src'] if last1 else '?'}); startup frames are listed separately.\n")

    # ---- bench + GPU frame time per run
    if meas1:
        L.append("## Wall-clock bench and GPU frame time per run (mode 1)\n")
        rows = []
        for r in meas1:
            b, w, pre = r["bench"], frame_stats(r["win"]), frame_stats(r["pre"])
            rows.append((r["name"], f"{b.get('avg_fps', 0):.1f}", f"{b.get('low1_fps', 0):.1f}", f"{b.get('median_ms', 0):.3f}",
                         f"{b.get('p95_ms', 0):.3f}", f"{b.get('p99_ms', 0):.3f}", f"{b.get('max_ms', 0):.2f}", int(b.get("hitches", 0)),
                         w["n"], f"{w['mean']:.3f}", f"{w['p95']:.3f}", f"{w['p99']:.3f}", f"{w['max']:.2f}", f"{pre['max']:.1f}"))
        stat = lambda f: [f(r) for r in meas1]
        rows.append(("**median [range]**", mr(stat(lambda r: r["bench"].get("avg_fps", 0)), "{:.1f}"),
                     mr(stat(lambda r: r["bench"].get("low1_fps", 0)), "{:.1f}"), mr(stat(lambda r: r["bench"].get("median_ms", 0))),
                     mr(stat(lambda r: r["bench"].get("p95_ms", 0))), mr(stat(lambda r: r["bench"].get("p99_ms", 0))),
                     mr(stat(lambda r: r["bench"].get("max_ms", 0)), "{:.2f}"), "", "",
                     mr(stat(lambda r: frame_stats(r["win"])["mean"])), mr(stat(lambda r: frame_stats(r["win"])["p95"])),
                     mr(stat(lambda r: frame_stats(r["win"])["p99"])), mr(stat(lambda r: frame_stats(r["win"])["max"]), "{:.2f}"),
                     mr(stat(lambda r: frame_stats(r["pre"])["max"]), "{:.1f}")))
        L.append(table(rows, ["run", "fps", "1% low", "wall med ms", "wall p95", "wall p99", "wall max", "hitches", "gpu frames",
                              "gpu mean ms", "gpu p95", "gpu p99", "gpu max", "startup gpu max"]))
        L.append("\n`startup gpu max` = worst GPU frame before the bench window (shader compile / cold caches / clock ramp).\n")
        if m1 and m1[0] is not meas1[0]:
            w0 = frame_stats(m1[0]["win"])
            L.append(f"Warm-up run ({m1[0]['name']}, excluded): fps {m1[0]['bench'].get('avg_fps', 0):.1f}, gpu mean {w0['mean']:.3f} ms.\n")

    # ---- telemetry
    if tele:
        L.append("## GPU clocks / temperature during the runs (nvidia-smi, 250 ms; clocks and reasons inside the bench window)\n")

        def win_cell(t, f):
            return f(t) if t["aligned"] and t["window_samples"] else "n/a"

        L.append(table([(n, f"{t['window_samples']}/{t['samples']}" if t["aligned"] else f"n/a/{t['samples']}",
                         win_cell(t, lambda t: f"{t['sm_mhz_min_window']:.0f}/{t['sm_mhz_mean_window']:.0f}"),
                         f"{t['sm_mhz_min_run']:.0f}", f"{t['temp_c_max']:.0f}", f"{t['power_w_mean']:.0f}",
                         win_cell(t, lambda t: f"{t['idle_bit_samples_window']}/{t['masks_window']}"),
                         win_cell(t, lambda t: reason_text(t["other_reason_bits_window"])))
                        for n, t in tele.items()],
                       ["run", "samples (window/run)", "sm MHz min/mean (window)", "sm MHz min (run)", "max C (run)", "mean W (run)",
                        "0x1 gpu idle (window)", "other reason bits (window)"]))
        L.append("")
        L.append("Window alignment, per run: " + "; ".join(sorted({t["align"] for t in tele.values()})) + ". "
                 "The idle bit 0x1 is reported separately from the other reason bits. Samples are 250 ms apart.\n")

    # ---- passes (bench window, per run)
    if meas1 and meas1[0]["win"]:
        cols = [c for c in meas1[0]["win"][0] if c.startswith("pass_") and c.endswith("_ms")]
        per = {c: [mean(fl(x[c]) for x in r["win"]) for r in meas1] for c in cols}
        p95 = {c: [pctl([fl(x[c]) for x in r["win"]], .95) for r in meas1] for c in cols}
        hit = {c: [100.0 * sum(1 for x in r["win"] if fl(x[c]) > 0) / max(1, len(r["win"])) for r in meas1] for c in cols}
        tot = med(frame_stats(r["win"])["mean"] for r in meas1) or 1.0
        L.append("## GPU passes ranked by average ms per frame (bench window, mode 1)\n")
        rows = []
        for c in sorted(cols, key=lambda c: -med(per[c]))[:30]:
            rows.append((c[5:-3], mr(per[c], "{:.4f}"), f"{100 * med(per[c]) / tot:.1f}%", f"{med(p95[c]):.3f}", f"{med(hit[c]):.0f}%"))
        L.append(table(rows, ["pass", "avg ms/frame", "share of gpu frame", "p95 ms", "hit"]))
        L.append("")
        groups = {
            "opaque scene": ["scene_opaque"], "sun maps + mask": ["sunshadow", "shadowmap", "flashshadow", "sunshadowmask", "flashmask"],
            "AO chain": ["ssao_depth", "ssao_ao", "ssao_blur1", "ssao_blur2", "ssao_apply", "ssao"],
            "SMAA + T2x": ["smaa_edges", "smaa_weights", "smaa_blend", "smaa_t2x", "smaa_t2x_reset", "smaa_t2x_resolve",
                           "smaa_t2x_copy_scene", "smaa_t2x_copy_history", "smaa_copy"],
            "bloom + grade": ["bloom_bright", "bloom_down", "bloom_up", "grade", "grade_copy"],
            "sun rays": ["rays_down", "rays_blur", "rays_add"], "depth prepass": ["prepass", "depthcopy"],
        }
        rows = []
        for gname, members in groups.items():
            have = [f"pass_{m}_ms" for m in members if f"pass_{m}_ms" in per]
            if have:
                v = [sum(per[c][i] for c in have) for i in range(len(meas1))]
                rows.append((gname, mr(v, "{:.4f}"), f"{100 * med(v) / tot:.1f}%", ", ".join(h[5:-3] for h in have)))
        L.append("### Grouped (disjoint; available cost, not achievable savings)\n")
        L.append(table(rows, ["group", "avg ms/frame", "share", "passes"]))
        L.append("")
        # T2x / grade split
        t2 = {k: med(per[f"pass_{k}_ms"]) for k in ("smaa_t2x_resolve", "smaa_t2x_copy_scene", "smaa_t2x_copy_history", "grade", "grade_copy")
              if f"pass_{k}_ms" in per}
        if t2:
            L.append("### T2x / grade copy split (are the copies the cost?)\n")
            L.append(table([(k, f"{v:.4f}") for k, v in t2.items()], ["mark", "median avg ms/frame"]))
            L.append("")

    # ---- CPU scopes
    if meas1 and meas1[0]["win"] and last1["cpu"]:
        cols = [c for c in meas1[0]["win"][0] if c.startswith("cpu_") and c.endswith("_ms")]
        per = {c: [mean(fl(x[c]) for x in r["win"]) for r in meas1] for c in cols}
        p95 = {c: [pctl([fl(x[c]) for x in r["win"]], .95) for r in meas1] for c in cols}
        info = {r["scope"]: r for r in last1["cpu"]}
        L.append("## CPU scopes per frame (bench window, mode 1; inclusive and nested - never sum; see README)\n")
        rows = []
        for c in cols:
            sc = c[4:-3]
            i = info.get(sc, {})
            rows.append((sc, mr(per[c], "{:.4f}"), f"{med(p95[c]):.3f}", i.get("calls_per_frame", ""), i.get("avg_us_per_call", "")))
        L.append(table(rows, ["scope", "avg ms/frame", "p95 ms", "calls/frame (all frames, last run)", "us/call"]))
        L.append("")
        # MDS breakdown
        def sc(name):
            return med(per.get(f"cpu_{name}_ms", [0.0]))
        mrows = []
        for part in ("bones", "lod_index", "skin", "tangent"):
            c, dp = sc(f"mds_{part}_color"), sc(f"mds_{part}_depth")
            mrows.append((part, f"{c:.4f}", f"{dp:.4f}", f"{c + dp:.4f}"))
        mrows.append(("prevpos", "-", f"{sc('mds_prevpos_depth'):.4f}", f"{sc('mds_prevpos_depth'):.4f}"))
        cnt = {r["counter"]: r for r in last1["counters"]}
        L.append("### MDS (animated characters) surface assembly: CPU ms/frame, main passes vs depth-fill passes\n")
        L.append(table(mrows, ["part", "color passes", "depth passes", "total"]))
        if cnt:
            L.append("")
            L.append(table([(k, v["avg_per_frame_bench_window"]) for k, v in cnt.items() if not k.startswith("mdslod_")],
                           ["counter", "per frame (bench window)"]))
        L.append("\nTangent cost is only incurred when the surface's shader wants ATTR_TANGENT; compare `mds_tangent_depth` against "
                 "`mds_tangent_color` and `mds_skin_*` to judge whether skipping tangents in depth passes is worth doing.\n")

    # ---- MDS LOD in depth views (C3 diagnostics; skipped for older sessions)
    if last1 and last1.get("mdslod"):
        L.extend(mds_lod_section(last1))

    # ---- cascades
    if last1 and last1["cascades"]:
        L.append("## Sun shadow cascades (last measured mode 1 run; all frames)\n")
        hdr = ["cascade", "rendered", "reused", "unseen"] + [f"re:{n}" for n in CASC_REASON_NAMES] + ["avg ms/render", "max ms"]
        rows = []
        for r in last1["cascades"]:
            rows.append([r["cascade"], r["frames_rendered"], r["frames_reused"], r["frames_unseen"]]
                        + [r.get("rerender_" + n, "0") for n in CASC_REASON_NAMES] + [r["avg_ms_when_rendered"], r["max_ms"]])
        L.append(table(rows, hdr))
        L.append("")
    if last2 and last2["cascades"]:
        L.append("### Cascade geometry per render (mode 2, last run; submitted batches/triangles, repeats included)\n")
        L.append(table([(r["cascade"], r["frames_rendered"], r["batches_per_render"], r["tris_per_render"], r["verts_per_render"],
                         r["gpu_batch_ms_per_render"], r["mds_batches_per_render"], r["mds_gpu_batch_ms_per_render"])
                        for r in last2["cascades"]],
                       ["cascade", "renders", "batches", "tris", "verts", "batch gpu ms", "mds batches", "mds batch gpu ms"]))
        L.append("")

    # ---- tail analysis
    if last1 and last1["win"]:
        win = last1["win"]
        cols = [c for c in win[0] if c.startswith("pass_") and c.endswith("_ms")]
        p95v = pctl([fl(x["gpu_ms"]) for x in win], .95)
        tail = [x for x in win if fl(x["gpu_ms"]) >= p95v]
        allm = mean(fl(x["gpu_ms"]) for x in win)
        tailm = mean(fl(x["gpu_ms"]) for x in tail)
        L.append(f"## Slow-frame tail (worst 5% of bench-window frames, last measured mode 1 run): {tailm:.3f} ms vs {allm:.3f} ms overall\n")
        rows = []
        excess = sorted(((mean(fl(x[c]) for x in tail) - mean(fl(x[c]) for x in win), c) for c in cols), reverse=True)
        total_ex = max(1e-9, tailm - allm)
        for ex, c in excess[:8]:
            rows.append((c[5:-3], f"{mean(fl(x[c]) for x in win):.4f}", f"{mean(fl(x[c]) for x in tail):.4f}", f"{ex:.4f}", f"{100 * ex / total_ex:.0f}%"))
        L.append(table(rows, ["pass", "overall ms", "tail ms", "excess ms", "share of excess"]))
        L.append("")
        bins = defaultdict(list)
        for x in win:
            bins[int(x["ref_time_ms"]) // 2000].append(x)
        hot = sorted(bins.items(), key=lambda kv: -mean(fl(x["gpu_ms"]) for x in kv[1]))[:6]
        rows = []
        for b, xs in hot:
            mid = xs[len(xs) // 2]
            top = max(cols, key=lambda c: mean(fl(x[c]) for x in xs))
            rows.append((f"{b * 2}-{b * 2 + 2} s", len(xs), f"{mean(fl(x['gpu_ms']) for x in xs):.3f}", f"{mid['x']} {mid['y']} {mid['z']}",
                         f"{mid.get('yaw', '?')} / {mid.get('pitch', '?')}", f"{top[5:-3]} {mean(fl(x[top]) for x in xs):.2f}"))
        L.append("### Hottest 2-second game-time windows (replay by game time, not by teleporting)\n")
        L.append(table(rows, ["game time", "frames", "gpu mean ms", "origin (mid frame)", "yaw / pitch", "top pass ms"]))
        L.append("")
        L.append("### Worst 15 frames in the bench window\n")
        rows = []
        for x in sorted(win, key=lambda r: -fl(r["gpu_ms"]))[:15]:
            top3 = sorted(cols, key=lambda c: -fl(x[c]))[:3]
            rows.append((x["frame"], x["ref_time_ms"], f"{x['x']} {x['y']} {x['z']}", f"{x.get('yaw', '?')} / {x.get('pitch', '?')}", x["gpu_ms"],
                         ", ".join(f"{c[5:-3]} {fl(x[c]):.2f}" for c in top3)))
        L.append(table(rows, ["frame", "game ms", "origin", "yaw / pitch", "gpu ms", "top passes (ms)"]))
        L.append("")

    # ---- mode 2
    shaders = last2["shaders"] if last2 else []
    if shaders:
        passes2 = last2["passes"]
        tot = defaultdict(lambda: defaultdict(float))
        for r in shaders:
            t = tot[r["shader"]]
            for k in ("gpu_ms_per_frame", "batches_per_frame", "tris_per_frame", "cpu_ms_per_frame", "draws_per_frame", "subdraws_per_frame"):
                t[k] += fl(r.get(k))
        frame_ms = fl(run2.get("gpu_avg_ms"), 1.0) or 1.0
        L.append(f"## Top 40 shaders by GPU time, summed over passes (mode 2 {last2['name']}, avg GPU frame {frame_ms:.2f} ms with profiling overhead; all frames)\n")
        top = sorted(tot.items(), key=lambda kv: -kv[1]["gpu_ms_per_frame"])[:40]
        L.append(table([(n, f"{v['gpu_ms_per_frame']:.4f}", f"{100 * v['gpu_ms_per_frame'] / frame_ms:.1f}%",
                         f"{v['batches_per_frame']:.1f}", f"{v['tris_per_frame']:.0f}", f"{v['draws_per_frame']:.1f}", f"{v['cpu_ms_per_frame']:.4f}")
                        for n, v in top], ["shader", "gpu ms/frame", "of frame", "batches", "tris", "draws", "cpu ms"]))
        L.append("")
        for title, key in (("entity kind", "kind"), ("stage iterator function", "iterator"), ("pass", "pass"), ("depth_fill (1 = depth-only draws)", "depth_fill")):
            agg = defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])
            for r in shaders:
                g = agg[r[key]]
                g[0] += fl(r["gpu_ms_per_frame"]); g[1] += fl(r["batches_per_frame"]); g[2] += fl(r["tris_per_frame"]); g[3] += fl(r.get("draws_per_frame"))
            L.append(f"### Batch GPU time by {title} (mode 2)\n")
            L.append(table([(k, f"{v[0]:.3f}", f"{v[1]:.0f}", f"{v[2]:.0f}", f"{v[3]:.1f}") for k, v in sorted(agg.items(), key=lambda kv: -kv[1][0])],
                           [key, "gpu ms/frame", "batches/frame", "tris/frame", "draws/frame"]))
            L.append("")
        fam = defaultdict(lambda: [0.0, 0.0])
        for n, v in tot.items():
            parts = n.replace("\\", "/").split("/")
            k = "/".join(parts[:2]) if len(parts) > 2 else n
            fam[k][0] += v["gpu_ms_per_frame"]; fam[k][1] += v["batches_per_frame"]
        L.append("### Shader families (first two path components), top 20 (mode 2)\n")
        L.append(table([(k, f"{v[0]:.3f}", f"{v[1]:.1f}") for k, v in sorted(fam.items(), key=lambda kv: -kv[1][0])[:20]],
                       ["family", "gpu ms/frame", "batches/frame"]))
        L.append("")
        L.append("### Heaviest shader per top pass (mode 2)\n")
        by_pass = defaultdict(list)
        for r in shaders:
            by_pass[r["pass"]].append(r)
        rows = []
        for p in sorted(passes2, key=lambda r: -fl(r["avg_ms_per_frame"]))[:8]:
            lst = sorted(by_pass.get(p["pass"], []), key=lambda r: -fl(r["gpu_ms_per_frame"]))[:5]
            rows.append((p["pass"], p["avg_ms_per_frame"], p.get("batch_ms_per_frame", ""), p.get("non_batch_ms_per_frame", ""),
                         "; ".join(f"{r['shader']} {r['gpu_ms_per_frame']}" for r in lst)))
        L.append(table(rows, ["pass", "ms/frame", "batch ms", "non-batch ms", "top shaders (ms/frame)"]))
        L.append("")

    L.append("## Reading notes\n")
    L.append("* mode1 = honest speed; mode2 = per-shader breakdown with inflated absolute times. Shader percentages are of the mode 2 frame.\n"
             "* `non-batch ms` of a pass = pass time minus draw batches: fullscreen work, clears, GPU idle gaps and timestamp overhead.\n"
             "* GPU buckets are timestamp intervals since the previous mark and can include idle gaps; CPU scopes are inclusive.\n"
             "* Ranges are across the measured repeats of this session only. For decisions use `scripts/profile-ab.sh` (interleaved A/B).\n"
             "* Full column documentation: `profiling/README.md`. Inputs that produced this data: `environment/`.\n")
