def load_run(rd: Path):
    r = {"name": rd.name, "dir": rd}
    r["frames"] = read_csv(rd / "frames.csv")
    r["passes"] = read_csv(rd / "passes.csv")
    r["cpu"] = read_csv(rd / "cpu_scopes.csv")
    r["counters"] = read_csv(rd / "counters.csv")
    r["cascades"] = read_csv(rd / "cascades.csv")
    r["shaders"] = read_csv(rd / "shaders.csv")
    r["mdslod"] = read_csv(rd / "mds_lod_summary.csv")  # absent in sessions from before C3
    r["mdslod_samples"] = read_csv(rd / "mds_lod.csv")
    r["run"] = json.loads((rd / "run.json").read_text()) if (rd / "run.json").is_file() else {}
    line = (rd / "bench_line.txt").read_text().strip() if (rd / "bench_line.txt").is_file() else ""
    r["bench_line"] = line
    r["bench"] = {k: fl(v) for k, v in (t.split("=", 1) for t in line.split() if "=" in t)}
    fr = r["frames"]
    if fr and "bench_window" in fr[0]:
        r["win"] = [x for x in fr if x["bench_window"] == "1"]
        r["pre"] = [x for x in fr if x["bench_window"] != "1"]
        r["window_src"] = "bench_window"
    else:  # old captures: skip the first 60 frames
        r["win"] = [x for x in fr if int(x["frame"]) >= 60]
        r["pre"] = [x for x in fr if int(x["frame"]) < 60]
        r["window_src"] = "first 60 frames skipped"
    return r


# nvidia-smi clocks_event_reasons bits (NVML nvmlClocksEventReason*)
NVML_REASON_BITS = {0x1: "gpu idle", 0x2: "app clocks", 0x4: "sw power cap", 0x8: "hw slowdown", 0x10: "sync boost",
                    0x20: "sw thermal", 0x40: "hw thermal", 0x80: "hw power brake", 0x100: "display clock"}


def num(s):
    """nvidia-smi value with its unit ('1845 MHz', '49.00 W', '27 %') -> float, or None"""
    try:
        return float(str(s).replace("MHz", "").replace("W", "").replace("%", "").strip())
    except (TypeError, ValueError):
        return None


def reason_text(masks):
    """{'0x4': 3} (reason masks without bit 0x1, hex -> samples) -> '0x4 x3 (sw power cap)'; 'none' when empty"""
    if not masks:
        return "none"
    return "; ".join(f"{k} x{n} ({'+'.join(NVML_REASON_BITS.get(1 << i, f'bit{i}') for i in range(16) if int(k, 16) >> i & 1)})"
                     for k, n in masks.items())


def telemetry(rd: Path, bench_secs: float):
    """gpu_telemetry.csv of one run. Window columns use the bench window: the telemetry rows carry wall-clock timestamps,
    frames.csv does not, so the window is bench_line.txt's mtime (written when the bench ends) minus its `seconds=`.
    Accurate to about one 250 ms sample at each edge. Without bench_line.txt the window is not aligned and says so."""
    p = rd / "gpu_telemetry.csv"
    if not p.is_file():
        return None
    with p.open() as f:
        rr = csv.reader(f)
        hdr = [h.strip() for h in next(rr, [])]
        rows = [dict(zip(hdr, [v.strip() for v in r])) for r in rr if r]
    if not rows:
        return None

    def col(rs, prefix):
        c = next((h for h in hdr if h.startswith(prefix)), None)
        return [v for v in (num(r.get(c)) for r in rs) if v is not None] if c else []

    reason_col = next((h for h in hdr if "event_reasons" in h or "throttle" in h), None)

    def mask(r):
        try:
            return int(r.get(reason_col, ""), 0) if reason_col else None
        except ValueError:
            return None

    stamped = []
    for r in rows:
        try:
            stamped.append((datetime.datetime.strptime(r.get("timestamp", ""), "%Y/%m/%d %H:%M:%S.%f").timestamp(), r))
        except ValueError:
            pass
    bl = rd / "bench_line.txt"
    aligned, win, align = False, [], "NOT aligned (no bench_line.txt or no parseable timestamps): window columns are n/a"
    if stamped and bench_secs and bl.is_file():
        end = bl.stat().st_mtime
        gap = end - max(t for t, _ in stamped)  # measured: +0.28 s in every captured run; far more means mtimes were lost
        if -1.0 <= gap <= 5.0:
            aligned = True
            win = [r for t, r in stamped if end - bench_secs <= t <= end]
            align = f"aligned: window = bench_line.txt mtime - {bench_secs:g} s (+-1 sample at each edge)"
        else:
            align = "NOT aligned: bench_line.txt mtime is not near the last telemetry sample (file mtimes lost in a copy? use cp -a)"
    sm_w, masks = col(win, "clocks.current.sm"), [m for m in map(mask, win) if m is not None]
    other = Counter(m & ~0x1 for m in masks if m & ~0x1)
    sm_all, temp, pw = col(rows, "clocks.current.sm") or col(rows, "clocks.sm"), col(rows, "temperature"), col(rows, "power")
    return {"samples": len(rows), "aligned": aligned, "align": align, "window_samples": len(win),
            "sm_mhz_min_window": min(sm_w) if sm_w else None, "sm_mhz_mean_window": mean(sm_w) if sm_w else None,
            "sm_mhz_min_run": min(sm_all) if sm_all else 0, "temp_c_max": max(temp) if temp else 0,
            "power_w_mean": mean(pw), "idle_bit_samples_window": sum(1 for m in masks if m & 0x1), "masks_window": len(masks),
            "other_reason_bits_window": {f"0x{m:x}": n for m, n in sorted(other.items())}}


def frame_stats(rows):
    g = [fl(x["gpu_ms"]) for x in rows]
    if not g:
        return {"n": 0, "mean": 0, "p50": 0, "p95": 0, "p99": 0, "max": 0}
    return {"n": len(g), "mean": mean(g), "p50": pctl(g, .5), "p95": pctl(g, .95), "p99": pctl(g, .99), "max": max(g)}


def mds_lod_section(run):
    """'MDS LOD in depth views' tables from mds_lod_summary.csv (whole run) and mds_lod.csv (sampled, bench window)."""
    L = ["## MDS LOD in depth views (last measured mode 1 run)\n",
         "Surfaces by view and LOD decision reason. `proj_nonpos`: RB_ProjectRadius returned 0 (full-LOD fallback); `flag_full`: "
         "REFLAG_FULL_LOD; `proj_clamped`: projected radius >= 1; `computed_full`: radius < 1 but LOD value still 1.0; "
         "`computed_reduced`: LOD < 1. Verts/tris are emitted vs the surface maximum. Whole run (warm-up included).\n"]
    rows = []
    tot = {}
    for r in run["mdslod"]:
        tot[r["view"]] = tot.get(r["view"], 0.0) + fl(r["surfaces"])
    for r in run["mdslod"]:
        n = fl(r["surfaces"])
        if not n:
            continue
        mv, ev = fl(r["max_verts"]), fl(r["emitted_verts"])
        mt, et = fl(r["max_tris"]), fl(r["emitted_tris"])
        rows.append((r["view"], r["reason"], f"{n:.0f}", f"{100 * n / tot[r['view']]:.1f}%", f"{ev:.0f}", f"{mv:.0f}",
                     f"{100 * ev / mv:.1f}%" if mv else "-", f"{et:.0f}", f"{mt:.0f}", f"{100 * et / mt:.1f}%" if mt else "-"))
    L.append(table(rows, ["view", "reason", "surfaces", "share of view", "emitted verts", "max verts", "verts %", "emitted tris",
                          "max tris", "tris %"]))
    L.append("")
    smp = run.get("mdslod_samples") or []
    win = run.get("win") or []
    if smp and win:
        t0 = min(fl(x["ref_time_ms"]) for x in win)
        t1 = max(fl(x["ref_time_ms"]) for x in win)
        smp = [x for x in smp if t0 <= fl(x["ref_time_ms"]) <= t1]
    if smp:
        L.append(f"### Sampled depth-view surfaces vs the main color pass (bench window, {len(smp)} samples)\n")
        agg = {}
        for x in smp:
            a = agg.setdefault((x["view"], x["reason"]), [0, 0, 0, 0, 0, 0.0])
            a[0] += 1
            a[1] += fl(x["emitted_verts"])
            a[2] += fl(x["max_verts"])
            if fl(x["main_verts"], -1) >= 0:
                a[3] += 1
                a[4] += fl(x["main_verts"])
                a[5] += fl(x["emitted_verts"])
        rows = []
        for (v, rs), a in sorted(agg.items()):
            rows.append((v, rs, a[0], f"{100 * a[1] / a[2]:.1f}%" if a[2] else "-", a[3],
                         f"{100 * a[5] / a[4]:.1f}%" if a[4] else "-"))
        L.append(table(rows, ["view", "reason", "samples", "emitted/max verts", "with main ref", "emitted vs main-pass verts"]))
        L.append("\n`emitted vs main-pass verts` > 100% means the depth view drew more detail than the main view did for the same "
                 "surface (reference = latest main color decision for that entity/surface, usually the previous frame).\n")
    return L


