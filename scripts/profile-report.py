def mget(meta, *keys):
    for k in keys:
        if meta.get(k) not in (None, ""):
            return meta[k]
    return None


def mem_has_data(r):
    return bool(r["objects"] or r["cats"] or r["vtl"] or r["ram"] or r["rtl"] or r["smi"])


def ram_val(r, section, item):
    for x in r["ram"]:
        if x.get("section") == section and x.get("item") == item:
            return fl(x.get("bytes"))
    return None


def bench_window_epochs(r):
    """(start_epoch_ms, end_epoch_ms) of the bench window from the VRAM/RAM timeline rows, None where unknown."""
    start = end = None
    for x in r["vtl"]:
        e = fl(x.get("epoch_ms"), None)
        if e is None:
            continue
        if start is None and x.get("bench") in ("1", 1):
            start = e
        end = e
    for x in r["rtl"]:
        e = fl(x.get("epoch_ms"), None)
        if e is not None and str(x.get("event", "")).startswith("bench_start") and start is None:
            start = e
        if e is not None and (end is None or e > end):
            end = e
    return start, end


def smi_series(r, col):
    """[(epoch_ms, value)] from memmon.csv (empty for csvs from before the epoch column)."""
    out = []
    for x in r["smi"]:
        e = fl(x.get("epoch_ms"), None)
        v = x.get(col, "")
        if e is not None and v not in ("", None):
            out.append((e, fl(v)))
    return out


def merged_timeline(r):
    """One row per sample of any source (engine RAM, renderer VRAM, memmon), sorted by epoch, with the latest value of every
    other source carried forward. Sizes in MB."""
    cols = ["ram_rss_mb", "ram_anon_mb", "ram_file_mb", "ram_hunk_used_mb", "ram_malloc_inuse_mb", "vram_total_mb", "vram_tex_mb",
            "vram_rt_mb", "vram_rb_mb", "vram_buf_mb", "vram_evict_count", "smi_rss_mb", "smi_anon_mb", "smi_vram_proc_mb",
            "smi_vram_total_mb"]
    ev = []
    for x in r["rtl"]:
        e = fl(x.get("epoch_ms"), None)
        if e is not None:
            ev.append((e, "engine", x.get("event", ""), "", {"ram_rss_mb": fl(x.get("rss")) / MB, "ram_anon_mb": fl(x.get("anon")) / MB,
                         "ram_file_mb": fl(x.get("file")) / MB, "ram_hunk_used_mb": fl(x.get("hunk_used")) / MB,
                         "ram_malloc_inuse_mb": fl(x.get("malloc_inuse")) / MB}))
    for x in r["vtl"]:
        e = fl(x.get("epoch_ms"), None)
        if e is not None:
            ev.append((e, "renderer", x.get("event", ""), x.get("bench", ""), {
                "vram_total_mb": fl(x.get("total")) / MB, "vram_tex_mb": fl(x.get("tex")) / MB, "vram_rt_mb": fl(x.get("rt")) / MB,
                "vram_rb_mb": fl(x.get("rb")) / MB, "vram_buf_mb": fl(x.get("buf")) / MB,
                "vram_evict_count": fl(x.get("nvx_evict_count"))}))
    for x in r["smi"]:
        e = fl(x.get("epoch_ms"), None)
        if e is not None:
            v = {"smi_rss_mb": fl(x.get("rss_mb")), "smi_anon_mb": fl(x.get("anon_mb")), "smi_vram_total_mb": fl(x.get("vram_total_mb"))}
            if x.get("vram_proc_mb", "") != "":
                v["smi_vram_proc_mb"] = fl(x.get("vram_proc_mb"))
            ev.append((e, "memmon", "", "", v))
    ev.sort(key=lambda t: t[0])
    if not ev:
        return [], []
    t0 = ev[0][0]
    cur, bench, rows = {}, "", []
    for e, src, event, b, vals in ev:
        cur.update(vals)
        if b != "":
            bench = b
        rows.append([f"{e:.0f}", f"{(e - t0) / 1000:.3f}", src, event, bench] + [f"{cur[c]:.2f}" if c in cur else "" for c in cols])
    return ["epoch_ms", "t_s", "source", "event", "bench"] + cols, rows


def write_csv(p: Path, header, rows):
    with p.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def session_categories(runs):
    """Median over the measured runs per VRAM category -> (header, rows) for mem_categories.csv."""
    per = defaultdict(lambda: defaultdict(list))
    for r in runs:
        for x in r["cats"]:
            c = x.get("category", "")
            per[c]["count"].append(fl(x.get("count")))
            per[c]["bytes"].append(fl(x.get("bytes")))
            per[c]["used"].append(fl(x.get("bytes_used_in_bench")))
    tot = sum(med(v["bytes"]) for v in per.values()) or 1.0
    rows = []
    for c, v in sorted(per.items(), key=lambda kv: -med(kv[1]["bytes"])):
        b = med(v["bytes"])
        rows.append([c, f"{med(v['count']):.0f}", f"{b:.0f}", f"{b / MB:.2f}", f"{100 * b / tot:.1f}", f"{med(v['used']):.0f}",
                     len(v["bytes"])])
    return ["category", "count", "bytes", "mb", "pct", "bytes_used_in_bench", "runs"], rows


def memory_section(d: Path):
    """('Memory' markdown lines, notes) for <d>/mem; writes mem_categories.csv and mem_timeline.csv. Empty list when there is no
    usable mem/ folder (sessions without profile.sh --mem, or a build without the memory profiler)."""
    md = d / "mem"
    if not md.is_dir():
        return []
    allruns = [load_mem_run(x) for x in sorted_runs(md)]
    allruns = [r for r in allruns if mem_has_data(r)]
    if not allruns:
        return ["## Memory\n", "`mem/` exists but holds no mem_*.csv files (engine built without the memory profiler, or "
                "`com_memProfile` did not take effect).\n"]
    runs = allruns[1:] if len(allruns) > 1 else allruns
    last = runs[-1]
    L = ["## Memory (RAM + VRAM census)\n"]
    meta = last["meta"]
    cv = meta.get("cvars", {}) if isinstance(meta.get("cvars"), dict) else {}
    L.append(f"Run `{last['name']}` of {len(allruns)} (run1 warm-up, {len(runs)} measured; categories are the median over the measured "
             f"runs, everything else is from `{last['name']}`). Resolution {mget(meta, 'resolution', 'res') or '?'}, GL "
             f"{mget(meta, 'gl_renderer', 'renderer', 'gl') or '?'}, NVX dedicated {mb(fl(mget(meta, 'nvx_dedicated_kb', 'nvx_dedicated')) * 1024)} MB. Cvars: "
             + (", ".join(f"{k} {v}" for k, v in cv.items()) or "n/a") + ".\n")

    start, end = bench_window_epochs(last)
    vtl = last["vtl"]
    # ---- VRAM accounted vs nvidia-smi
    if vtl or last["smi"]:
        endrow = next((x for x in reversed(vtl) if str(x.get("event", "")).startswith("bench_end")), vtl[-1] if vtl else None)
        acc = fl(endrow.get("total")) if endrow else None
        proc = smi_series(last, "vram_proc_mb")
        smi_at = None
        if proc and endrow and endrow.get("epoch_ms"):
            e = fl(endrow["epoch_ms"])
            smi_at = min(proc, key=lambda t: abs(t[0] - e))[1]
        elif proc:
            smi_at = proc[-1][1]
        evc = [fl(x.get("nvx_evict_count")) for x in vtl if x.get("nvx_evict_count", "") != ""]
        L.append("### VRAM: accounted vs driver\n")
        rows = []
        if acc is not None:
            rows.append(("accounted by the census (" + str(endrow.get("event", "?")) + " row)", f"{acc / MB:.0f} MB"))
            for k, label in (("tex", "textures"), ("rt", "render-target textures"), ("rb", "renderbuffers"), ("buf", "buffers (VAO/VBO)"),
                             ("est", "estimates (loadscreen, default fb)")):
                if endrow.get(k, "") != "":
                    rows.append((f"  of which {label}", f"{fl(endrow[k]) / MB:.0f} MB"))
        if smi_at is not None:
            rows.append(("nvidia-smi, this process (sample nearest that row)", f"{smi_at:.0f} MB"))
            if acc is not None:
                rows.append(("unaccounted remainder (driver, context, alignment, fragmentation)", f"{smi_at - acc / MB:.0f} MB ({100 * (smi_at - acc / MB) / smi_at:.0f}% of the process)" if smi_at else "-"))
        elif last["smi"]:
            rows.append(("nvidia-smi, this process", "n/a (driver did not list the process, or memmon.csv has no epoch column)"))
        if proc:
            rows.append(("nvidia-smi process peak over the run", f"{max(v for _, v in proc):.0f} MB"))
        if evc:
            rows.append(("driver evictions (NVX evict count) during the run", f"{evc[-1] - evc[0]:.0f}"
                         + (f" (evicted {(fl(vtl[-1].get('nvx_evicted_kb')) - fl(vtl[0].get('nvx_evicted_kb'))) / 1024:.0f} MB)"
                            if vtl[-1].get("nvx_evicted_kb", "") != "" else "")))
        if mget(meta, 'nvx_dedicated_kb', 'nvx_dedicated'):
            rows.append(("dedicated VRAM of the GPU (NVX)", f"{fl(mget(meta, 'nvx_dedicated_kb', 'nvx_dedicated')) / 1024:.0f} MB"))
        L.append(table(rows, ["item", "value"]))
        L.append("\nThe census is analytic (see the plan): rows marked estimate are not measured; the remainder is the sum of what "
                 "the formulas cannot see. Evictions > 0 mean the driver ran out of VRAM and swapped.\n")

    # ---- categories (session csv + ranking)
    hdr, crow = session_categories(runs)
    if crow:
        write_csv(d / "mem_categories.csv", hdr, crow)
        L.append("### VRAM by category (median over measured runs)\n")
        L.append(table([(c[0], c[1], c[3], c[4] + "%", f"{fl(c[5]) / MB:.1f}", f"{(fl(c[2]) - fl(c[5])) / MB:.1f}") for c in crow[:25]],
                       ["category", "objects", "MB", "share", "MB used in bench", "MB unused in bench"]))
        L.append("")
    objs = last["objects"]
    if objs:
        tex = [o for o in objs if o.get("kind") == "texture"]
        by_pak = defaultdict(lambda: [0, 0.0, 0.0])
        for o in tex:
            g = by_pak[o.get("pak") or "-"]
            g[0] += 1; g[1] += max(0.0, fl(o.get("bytes"))); g[2] += max(0.0, fl(o.get("bytes"))) if o.get("used_in_bench") in ("1", 1) else 0.0
        if by_pak:
            L.append(f"### Texture VRAM by source pak ({last['name']}; `dir` = loose files, `-` = not file-backed)\n")
            L.append(table([(k, v[0], f"{v[1] / MB:.1f}", f"{v[2] / MB:.1f}") for k, v in sorted(by_pak.items(), key=lambda kv: -kv[1][1])[:15]],
                           ["pak", "images", "MB", "MB used in bench"]))
            L.append("")
        by_map = defaultdict(lambda: [0, 0.0])
        for o in tex:
            g = by_map[(o.get("category", ""), o.get("map") or "-")]
            g[0] += 1; g[1] += max(0.0, fl(o.get("bytes")))
        if by_map:
            L.append("### Texture VRAM by category and map type (diffuse / normal / spec)\n")
            L.append(table([(k[0], k[1], v[0], f"{v[1] / MB:.1f}") for k, v in sorted(by_map.items(), key=lambda kv: -kv[1][1])[:20]],
                           ["category", "map", "images", "MB"]))
            L.append("")
        unk = [o for o in objs if fl(o.get("bytes")) < 0]
        if unk:
            L.append(f"**{len(unk)} object(s) have an unknown format (bytes -1) and are not in any total**, e.g. "
                     + ", ".join(f"`{o.get('name')}`" for o in unk[:5]) + ".\n")
        L.append("### Top 25 VRAM objects\n")
        top = sorted(objs, key=lambda o: -fl(o.get("bytes")))[:25]
        L.append(table([(o.get("kind"), o.get("category"), o.get("map"), o.get("pak"), f"`{o.get('name')}`",
                         f"{o.get('width')}x{o.get('height')}" + (f"x{o['faces']}" if o.get("faces") not in (None, "", "1") else ""),
                         o.get("format"), mb(o.get("bytes")), o.get("used_in_bench"), o.get("note", "")) for o in top],
                       ["kind", "category", "map", "pak", "name", "size", "format", "MB", "used in bench", "note"]))
        L.append("")
        unused = [o for o in objs if o.get("used_in_bench") in ("0", 0) and fl(o.get("bytes")) > 0]
        if any(o.get("used_in_bench", "") != "" for o in objs):
            ub = sum(fl(o["bytes"]) for o in unused)
            allb = sum(fl(o["bytes"]) for o in objs if fl(o.get("bytes")) > 0) or 1.0
            L.append(f"### Resident but not used in the bench window: {ub / MB:.0f} MB ({100 * ub / allb:.0f}% of the census, {len(unused)} objects)\n")
            L.append("Candidates for lazy loading or smaller formats; `used` means bound at least once after the bench started, so "
                     "things used only during load or by another part of the level show up here.\n")
            L.append(table([(o.get("category"), o.get("pak"), f"`{o.get('name')}`", f"{o.get('width')}x{o.get('height')}", o.get("format"), mb(o.get("bytes")))
                            for o in sorted(unused, key=lambda o: -fl(o["bytes"]))[:15]],
                           ["category", "pak", "name", "size", "format", "MB"]))
            L.append("")

    # ---- RAM
    ram = last["ram"]
    if ram:
        L.append("### RAM: rollup decomposition\n")
        sec = defaultdict(list)
        for x in ram:
            sec[x.get("section", "")].append(x)
        roll = {x["item"]: fl(x["bytes"]) for x in sec.get("rollup", [])}
        rows = [(k, mb(roll[k])) for k in ("rss", "anon", "file", "shmem") if k in roll]
        L.append(table(rows, ["rollup", "MB"]))
        L.append("")
        for title, key, n in (("Anonymous memory (smaps_anon)", "smaps_anon", 12), ("File-backed mappings, top (smaps_file)", "smaps_file", 8),
                              ("Device / memfd mappings (smaps_dev)", "smaps_dev", 6)):
            if sec.get(key):
                L.append(f"**{title}**\n")
                L.append(table([(x["item"], mb(x["bytes"]), x.get("note", "")) for x in sorted(sec[key], key=lambda x: -fl(x["bytes"]))[:n]],
                               ["item", "MB", "note"]))
                L.append("")
        if sec.get("derived"):
            L.append("**Derived**: " + "; ".join(f"{x['item']} {mb(x['bytes'])} MB" for x in sec["derived"]) +
                     ". `unattributed_anon` = anon RSS minus the attributed anonymous mappings; `profiler_overhead` is the profiler's own memory.\n")
        if sec.get("hunk"):
            L.append("**Hunk**: " + "; ".join(f"{x['item']} {mb(x['bytes'])} MB" for x in sec["hunk"]) + "\n")
        if sec.get("hunk_phase"):
            L.append("**Hunk by load phase** (delta of hunk use between load marks; the hunk is cleared on each map load)\n")
            L.append(table([(x["item"], mb(x["bytes"]), x.get("note", "")) for x in sec["hunk_phase"]], ["phase", "MB", "note"]))
            L.append("")
        nested = sec.get("malloc", []) + sec.get("sound", [])
        if nested:
            L.append("**Nested values (parts of anon/file RSS already counted above, never add them to the rollup)**: "
                     + "; ".join(f"{x['section']}.{x['item']} {mb(x['bytes'])} MB" for x in nested) + "\n")

    # ---- load peak vs steady state vs bench end
    rtl = last["rtl"]
    if rtl or vtl or last["smi"]:
        L.append("### Load peak vs steady state vs bench end\n")
        rows = []

        def pick(series, lo, hi):
            return [v for e, v in series if (lo is None or e >= lo) and (hi is None or e < hi)]

        rss = [(fl(x.get("epoch_ms")), fl(x.get("rss")) / MB) for x in rtl if x.get("epoch_ms")]
        vt = [(fl(x.get("epoch_ms")), fl(x.get("total")) / MB) for x in vtl if x.get("epoch_ms")]
        sp = smi_series(last, "vram_proc_mb")
        sr = smi_series(last, "rss_mb")
        for name, ser in (("RAM RSS (engine rows)", rss), ("RAM RSS (memmon)", sr), ("VRAM accounted (renderer rows)", vt),
                          ("VRAM process (nvidia-smi)", sp)):
            if not ser:
                continue
            pre = pick(ser, None, start)
            win = pick(ser, start, None)
            rows.append((name, f"{max(pre):.0f}" if pre else "-", f"{pre[-1]:.0f}" if pre else "-",
                         f"{med(win):.0f}" if win else "-", f"{ser[-1][1]:.0f}", f"{max(v for _, v in ser):.0f}"))
        if rows:
            L.append(table(rows, ["MB", "load peak (before bench)", "end of load (steady start)", "bench window median", "last sample", "overall peak"]))
            L.append("\nLoad peak > steady state means memory was freed after loading (temporary decode buffers, hunk temp); "
                     "a bench-end value above the bench-start one means growth during play (leaks, lazy uploads).\n")
        if not start:
            L.append("The bench-start edge is unknown (no `bench=1` renderer row), so the load/bench split above uses the whole run as load.\n")

    # ---- merged timeline csv
    hdr, rows = merged_timeline(last)
    if rows:
        write_csv(d / "mem_timeline.csv", hdr, rows)
        L.append(f"Files: `mem_categories.csv` (median over measured runs), `mem_timeline.csv` ({len(rows)} rows of {last['name']}: engine RAM, "
                 "renderer VRAM and memmon samples merged by epoch, latest values carried forward), raw per-run files in `mem/runK/`.\n")
    return L


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--label", default="")
    ap.add_argument("--args", default="")
    a = ap.parse_args()
    d = Path(a.dir)
    (d.parent / "README.md").write_text(README)

    m1 = [load_run(x) for x in sorted_runs(d / "mode1")]
    m2 = [load_run(x) for x in sorted_runs(d / "mode2")]
    meas1 = m1[1:] if len(m1) > 1 else m1
    meas2 = m2[1:] if len(m2) > 1 else m2
    last1 = meas1[-1] if meas1 else None
    last2 = meas2[-1] if meas2 else None
    run1 = last1["run"] if last1 else {}
    run2 = last2["run"] if last2 else {}
    tele = {}  # keyed by mode and run: mode2 runs share the run names of mode1
    for r in m1 + m2:
        t = telemetry(r["dir"], r["bench"].get("seconds", 0.0))
        if t:
            tele[f"{r['dir'].parent.name}/{r['name']}"] = t

    meta = {
        "created": time.strftime("%Y-%m-%d %H:%M:%S"), "label": a.label, "extra_bench_args": a.args,
        "git_outer": sh(["git", "rev-parse", "--short", "HEAD"]),
        "git_engine": sh(["git", "rev-parse", "--short", "HEAD"], ROOT / "iortcw"),
        "git_dirty": bool(sh(["git", "status", "--porcelain"]) or sh(["git", "status", "--porcelain"], ROOT / "iortcw")),
        "host": platform.node(), "kernel": platform.release(),
        "gpu_smi": sh(["nvidia-smi", "--query-gpu=name,driver_version,clocks.max.sm,power.limit", "--format=csv,noheader"]),
        "protocol": {"mode1_runs": len(m1), "mode1_measured": [r["name"] for r in meas1], "mode2_runs": len(m2),
                     "mode2_measured": [r["name"] for r in meas2], "warmup": "run1 of each mode",
                     "window": last1["window_src"] if last1 else ""},
        "environment_dir": "environment/",
        "gpu_telemetry": tele,
        "mode1_run": run1, "mode2_run": run2,
        "caveats": [
            "mode1 FPS/pass times are real; mode2 adds timestamp pairs per draw batch (~8% slower), so its absolute times are inflated "
            "and must not be subtracted from mode1",
            "GPU pass buckets are timestamp intervals since the previous mark: they include GPU idle gaps while the CPU submits work",
            "CPU scopes are inclusive and nested: never sum them; swap time is charged to the next frame",
            "headless gamescope run; resolution is the bench headless size, not necessarily the user's display",
            f"{len(meas1)} measured mode1 run(s): ranges describe run-to-run variation, not a confidence interval",
        ],
    }
    (d / "meta.json").write_text(json.dumps(meta, indent=1))

    L = []
    L.append(f"# Render profile: {a.label}\n")
    L.append(f"Session `{d.name}` - engine {meta['git_engine']}, outer {meta['git_outer']}{' (dirty tree, diffs in environment/)' if meta['git_dirty'] else ''}, "
             f"{run1.get('resolution', '?')} on {run1.get('gl_renderer', '?')}; r_frameWarp {run1.get('r_frameWarp', '?')}, "
             f"r_aa {run1.get('r_aa', '?')}, r_ao {run1.get('r_ao', '?')}. Extra bench args: `{a.args or 'none'}`.\n")
    L.append(f"Protocol: mode 1 = {len(m1)} runs (run1 warm-up, {len(meas1)} measured), mode 2 = {len(m2)} runs. Every figure below is "
             f"`median [min-max]` over the measured mode 1 runs unless marked otherwise. Frame statistics cover the bench window "
             f"({last1['window_src'] if last1 else '?'}); startup frames are listed separately.\n")

    # ---- bench + GPU frame time per run
    if meas1:
        L.append("## Wall-clock bench and GPU frame time per run (mode 1)\n")
        rows = []
        for r in meas1:
            b, w, pre = r["bench"], frame_stats(r["win"]), frame_stats(r["pre"])
            rows.append((r["name"], f"{b.get('avg_fps', 0):.1f}", f"{b.get('low1_fps', 0):.1f}", f"{b.get('median_ms', 0):.3f}",
                         f"{b.get('p95_ms', 0):.3f}", f"{b.get('p99_ms', 0):.3f}", f"{b.get('max_ms', 0):.2f}", int(b.get("hitches", 0)),
                         w["n"], f"{w['mean']:.3f}", f"{w['p95']:.3f}", f"{w['p99']:.3f}", f"{w['max']:.2f}", f"{pre['max']:.1f}"))
        stat = lambda f: [f(r) for r in meas1]
        rows.append(("**median [range]**", mr(stat(lambda r: r["bench"].get("avg_fps", 0)), "{:.1f}"),
                     mr(stat(lambda r: r["bench"].get("low1_fps", 0)), "{:.1f}"), mr(stat(lambda r: r["bench"].get("median_ms", 0))),
                     mr(stat(lambda r: r["bench"].get("p95_ms", 0))), mr(stat(lambda r: r["bench"].get("p99_ms", 0))),
                     mr(stat(lambda r: r["bench"].get("max_ms", 0)), "{:.2f}"), "", "",
                     mr(stat(lambda r: frame_stats(r["win"])["mean"])), mr(stat(lambda r: frame_stats(r["win"])["p95"])),
                     mr(stat(lambda r: frame_stats(r["win"])["p99"])), mr(stat(lambda r: frame_stats(r["win"])["max"]), "{:.2f}"),
                     mr(stat(lambda r: frame_stats(r["pre"])["max"]), "{:.1f}")))
        L.append(table(rows, ["run", "fps", "1% low", "wall med ms", "wall p95", "wall p99", "wall max", "hitches", "gpu frames",
                              "gpu mean ms", "gpu p95", "gpu p99", "gpu max", "startup gpu max"]))
        L.append("\n`startup gpu max` = worst GPU frame before the bench window (shader compile / cold caches / clock ramp).\n")
        if m1 and m1[0] is not meas1[0]:
            w0 = frame_stats(m1[0]["win"])
            L.append(f"Warm-up run ({m1[0]['name']}, excluded): fps {m1[0]['bench'].get('avg_fps', 0):.1f}, gpu mean {w0['mean']:.3f} ms.\n")

    # ---- telemetry
    if tele:
        L.append("## GPU clocks / temperature during the runs (nvidia-smi, 250 ms; clocks and reasons inside the bench window)\n")

        def win_cell(t, f):
            return f(t) if t["aligned"] and t["window_samples"] else "n/a"

        L.append(table([(n, f"{t['window_samples']}/{t['samples']}" if t["aligned"] else f"n/a/{t['samples']}",
                         win_cell(t, lambda t: f"{t['sm_mhz_min_window']:.0f}/{t['sm_mhz_mean_window']:.0f}"),
                         f"{t['sm_mhz_min_run']:.0f}", f"{t['temp_c_max']:.0f}", f"{t['power_w_mean']:.0f}",
                         win_cell(t, lambda t: f"{t['idle_bit_samples_window']}/{t['masks_window']}"),
                         win_cell(t, lambda t: reason_text(t["other_reason_bits_window"])))
                        for n, t in tele.items()],
                       ["run", "samples (window/run)", "sm MHz min/mean (window)", "sm MHz min (run)", "max C (run)", "mean W (run)",
                        "0x1 gpu idle (window)", "other reason bits (window)"]))
        L.append("")
        L.append("Window alignment, per run: " + "; ".join(sorted({t["align"] for t in tele.values()})) + ". "
                 "The idle bit 0x1 is reported separately from the other reason bits. Samples are 250 ms apart.\n")

    # ---- passes (bench window, per run)
    if meas1 and meas1[0]["win"]:
        cols = [c for c in meas1[0]["win"][0] if c.startswith("pass_") and c.endswith("_ms")]
        per = {c: [mean(fl(x[c]) for x in r["win"]) for r in meas1] for c in cols}
        p95 = {c: [pctl([fl(x[c]) for x in r["win"]], .95) for r in meas1] for c in cols}
        hit = {c: [100.0 * sum(1 for x in r["win"] if fl(x[c]) > 0) / max(1, len(r["win"])) for r in meas1] for c in cols}
        tot = med(frame_stats(r["win"])["mean"] for r in meas1) or 1.0
        L.append("## GPU passes ranked by average ms per frame (bench window, mode 1)\n")
        rows = []
        for c in sorted(cols, key=lambda c: -med(per[c]))[:30]:
            rows.append((c[5:-3], mr(per[c], "{:.4f}"), f"{100 * med(per[c]) / tot:.1f}%", f"{med(p95[c]):.3f}", f"{med(hit[c]):.0f}%"))
        L.append(table(rows, ["pass", "avg ms/frame", "share of gpu frame", "p95 ms", "hit"]))
        L.append("")
        groups = {
            "opaque scene": ["scene_opaque"], "sun maps + mask": ["sunshadow", "shadowmap", "flashshadow", "sunshadowmask", "flashmask"],
            "AO chain": ["ssao_depth", "ssao_ao", "ssao_blur1", "ssao_blur2", "ssao_apply", "ssao"],
            "SMAA + T2x": ["smaa_edges", "smaa_weights", "smaa_blend", "smaa_t2x", "smaa_t2x_reset", "smaa_t2x_resolve",
                           "smaa_t2x_copy_scene", "smaa_t2x_copy_history", "smaa_copy"],
            "bloom + grade": ["bloom_bright", "bloom_down", "bloom_up", "grade", "grade_copy"],
            "sun rays": ["rays_down", "rays_blur", "rays_add"], "depth prepass": ["prepass", "depthcopy"],
        }
        rows = []
        for gname, members in groups.items():
            have = [f"pass_{m}_ms" for m in members if f"pass_{m}_ms" in per]
            if have:
                v = [sum(per[c][i] for c in have) for i in range(len(meas1))]
                rows.append((gname, mr(v, "{:.4f}"), f"{100 * med(v) / tot:.1f}%", ", ".join(h[5:-3] for h in have)))
        L.append("### Grouped (disjoint; available cost, not achievable savings)\n")
        L.append(table(rows, ["group", "avg ms/frame", "share", "passes"]))
        L.append("")
        # T2x / grade split
        t2 = {k: med(per[f"pass_{k}_ms"]) for k in ("smaa_t2x_resolve", "smaa_t2x_copy_scene", "smaa_t2x_copy_history", "grade", "grade_copy")
              if f"pass_{k}_ms" in per}
        if t2:
            L.append("### T2x / grade copy split (are the copies the cost?)\n")
            L.append(table([(k, f"{v:.4f}") for k, v in t2.items()], ["mark", "median avg ms/frame"]))
            L.append("")

    # ---- CPU scopes
    if meas1 and meas1[0]["win"] and last1["cpu"]:
        cols = [c for c in meas1[0]["win"][0] if c.startswith("cpu_") and c.endswith("_ms")]
        per = {c: [mean(fl(x[c]) for x in r["win"]) for r in meas1] for c in cols}
        p95 = {c: [pctl([fl(x[c]) for x in r["win"]], .95) for r in meas1] for c in cols}
        info = {r["scope"]: r for r in last1["cpu"]}
        L.append("## CPU scopes per frame (bench window, mode 1; inclusive and nested - never sum; see README)\n")
        rows = []
        for c in cols:
            sc = c[4:-3]
            i = info.get(sc, {})
            rows.append((sc, mr(per[c], "{:.4f}"), f"{med(p95[c]):.3f}", i.get("calls_per_frame", ""), i.get("avg_us_per_call", "")))
        L.append(table(rows, ["scope", "avg ms/frame", "p95 ms", "calls/frame (all frames, last run)", "us/call"]))
        L.append("")
        # MDS breakdown
        def sc(name):
            return med(per.get(f"cpu_{name}_ms", [0.0]))
        mrows = []
        for part in ("bones", "lod_index", "skin", "tangent"):
            c, dp = sc(f"mds_{part}_color"), sc(f"mds_{part}_depth")
            mrows.append((part, f"{c:.4f}", f"{dp:.4f}", f"{c + dp:.4f}"))
        mrows.append(("prevpos", "-", f"{sc('mds_prevpos_depth'):.4f}", f"{sc('mds_prevpos_depth'):.4f}"))
        cnt = {r["counter"]: r for r in last1["counters"]}
        L.append("### MDS (animated characters) surface assembly: CPU ms/frame, main passes vs depth-fill passes\n")
        L.append(table(mrows, ["part", "color passes", "depth passes", "total"]))
        if cnt:
            L.append("")
            L.append(table([(k, v["avg_per_frame_bench_window"]) for k, v in cnt.items() if not k.startswith("mdslod_")],
                           ["counter", "per frame (bench window)"]))
        L.append("\nTangent cost is only incurred when the surface's shader wants ATTR_TANGENT; compare `mds_tangent_depth` against "
                 "`mds_tangent_color` and `mds_skin_*` to judge whether skipping tangents in depth passes is worth doing.\n")

    # ---- MDS LOD in depth views (C3 diagnostics; skipped for older sessions)
    if last1 and last1.get("mdslod"):
        L.extend(mds_lod_section(last1))

    # ---- cascades
    if last1 and last1["cascades"]:
        L.append("## Sun shadow cascades (last measured mode 1 run; all frames)\n")
        hdr = ["cascade", "rendered", "reused", "unseen"] + [f"re:{n}" for n in CASC_REASON_NAMES] + ["avg ms/render", "max ms"]
        rows = []
        for r in last1["cascades"]:
            rows.append([r["cascade"], r["frames_rendered"], r["frames_reused"], r["frames_unseen"]]
                        + [r.get("rerender_" + n, "0") for n in CASC_REASON_NAMES] + [r["avg_ms_when_rendered"], r["max_ms"]])
        L.append(table(rows, hdr))
        L.append("")
    if last2 and last2["cascades"]:
        L.append("### Cascade geometry per render (mode 2, last run; submitted batches/triangles, repeats included)\n")
        L.append(table([(r["cascade"], r["frames_rendered"], r["batches_per_render"], r["tris_per_render"], r["verts_per_render"],
                         r["gpu_batch_ms_per_render"], r["mds_batches_per_render"], r["mds_gpu_batch_ms_per_render"])
                        for r in last2["cascades"]],
                       ["cascade", "renders", "batches", "tris", "verts", "batch gpu ms", "mds batches", "mds batch gpu ms"]))
        L.append("")

    # ---- tail analysis
    if last1 and last1["win"]:
        win = last1["win"]
        cols = [c for c in win[0] if c.startswith("pass_") and c.endswith("_ms")]
        p95v = pctl([fl(x["gpu_ms"]) for x in win], .95)
        tail = [x for x in win if fl(x["gpu_ms"]) >= p95v]
        allm = mean(fl(x["gpu_ms"]) for x in win)
        tailm = mean(fl(x["gpu_ms"]) for x in tail)
        L.append(f"## Slow-frame tail (worst 5% of bench-window frames, last measured mode 1 run): {tailm:.3f} ms vs {allm:.3f} ms overall\n")
        rows = []
        excess = sorted(((mean(fl(x[c]) for x in tail) - mean(fl(x[c]) for x in win), c) for c in cols), reverse=True)
        total_ex = max(1e-9, tailm - allm)
        for ex, c in excess[:8]:
            rows.append((c[5:-3], f"{mean(fl(x[c]) for x in win):.4f}", f"{mean(fl(x[c]) for x in tail):.4f}", f"{ex:.4f}", f"{100 * ex / total_ex:.0f}%"))
        L.append(table(rows, ["pass", "overall ms", "tail ms", "excess ms", "share of excess"]))
        L.append("")
        bins = defaultdict(list)
        for x in win:
            bins[int(x["ref_time_ms"]) // 2000].append(x)
        hot = sorted(bins.items(), key=lambda kv: -mean(fl(x["gpu_ms"]) for x in kv[1]))[:6]
        rows = []
        for b, xs in hot:
            mid = xs[len(xs) // 2]
            top = max(cols, key=lambda c: mean(fl(x[c]) for x in xs))
            rows.append((f"{b * 2}-{b * 2 + 2} s", len(xs), f"{mean(fl(x['gpu_ms']) for x in xs):.3f}", f"{mid['x']} {mid['y']} {mid['z']}",
                         f"{mid.get('yaw', '?')} / {mid.get('pitch', '?')}", f"{top[5:-3]} {mean(fl(x[top]) for x in xs):.2f}"))
        L.append("### Hottest 2-second game-time windows (replay by game time, not by teleporting)\n")
        L.append(table(rows, ["game time", "frames", "gpu mean ms", "origin (mid frame)", "yaw / pitch", "top pass ms"]))
        L.append("")
        L.append("### Worst 15 frames in the bench window\n")
        rows = []
        for x in sorted(win, key=lambda r: -fl(r["gpu_ms"]))[:15]:
            top3 = sorted(cols, key=lambda c: -fl(x[c]))[:3]
            rows.append((x["frame"], x["ref_time_ms"], f"{x['x']} {x['y']} {x['z']}", f"{x.get('yaw', '?')} / {x.get('pitch', '?')}", x["gpu_ms"],
                         ", ".join(f"{c[5:-3]} {fl(x[c]):.2f}" for c in top3)))
        L.append(table(rows, ["frame", "game ms", "origin", "yaw / pitch", "gpu ms", "top passes (ms)"]))
        L.append("")

    # ---- mode 2
    shaders = last2["shaders"] if last2 else []
    if shaders:
        passes2 = last2["passes"]
        tot = defaultdict(lambda: defaultdict(float))
        for r in shaders:
            t = tot[r["shader"]]
            for k in ("gpu_ms_per_frame", "batches_per_frame", "tris_per_frame", "cpu_ms_per_frame", "draws_per_frame", "subdraws_per_frame"):
                t[k] += fl(r.get(k))
        frame_ms = fl(run2.get("gpu_avg_ms"), 1.0) or 1.0
        L.append(f"## Top 40 shaders by GPU time, summed over passes (mode 2 {last2['name']}, avg GPU frame {frame_ms:.2f} ms with profiling overhead; all frames)\n")
        top = sorted(tot.items(), key=lambda kv: -kv[1]["gpu_ms_per_frame"])[:40]
        L.append(table([(n, f"{v['gpu_ms_per_frame']:.4f}", f"{100 * v['gpu_ms_per_frame'] / frame_ms:.1f}%",
                         f"{v['batches_per_frame']:.1f}", f"{v['tris_per_frame']:.0f}", f"{v['draws_per_frame']:.1f}", f"{v['cpu_ms_per_frame']:.4f}")
                        for n, v in top], ["shader", "gpu ms/frame", "of frame", "batches", "tris", "draws", "cpu ms"]))
        L.append("")
        for title, key in (("entity kind", "kind"), ("stage iterator function", "iterator"), ("pass", "pass"), ("depth_fill (1 = depth-only draws)", "depth_fill")):
            agg = defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])
            for r in shaders:
                g = agg[r[key]]
                g[0] += fl(r["gpu_ms_per_frame"]); g[1] += fl(r["batches_per_frame"]); g[2] += fl(r["tris_per_frame"]); g[3] += fl(r.get("draws_per_frame"))
            L.append(f"### Batch GPU time by {title} (mode 2)\n")
            L.append(table([(k, f"{v[0]:.3f}", f"{v[1]:.0f}", f"{v[2]:.0f}", f"{v[3]:.1f}") for k, v in sorted(agg.items(), key=lambda kv: -kv[1][0])],
                           [key, "gpu ms/frame", "batches/frame", "tris/frame", "draws/frame"]))
            L.append("")
        fam = defaultdict(lambda: [0.0, 0.0])
        for n, v in tot.items():
            parts = n.replace("\\", "/").split("/")
            k = "/".join(parts[:2]) if len(parts) > 2 else n
            fam[k][0] += v["gpu_ms_per_frame"]; fam[k][1] += v["batches_per_frame"]
        L.append("### Shader families (first two path components), top 20 (mode 2)\n")
        L.append(table([(k, f"{v[0]:.3f}", f"{v[1]:.1f}") for k, v in sorted(fam.items(), key=lambda kv: -kv[1][0])[:20]],
                       ["family", "gpu ms/frame", "batches/frame"]))
        L.append("")
        L.append("### Heaviest shader per top pass (mode 2)\n")
        by_pass = defaultdict(list)
        for r in shaders:
            by_pass[r["pass"]].append(r)
        rows = []
        for p in sorted(passes2, key=lambda r: -fl(r["avg_ms_per_frame"]))[:8]:
            lst = sorted(by_pass.get(p["pass"], []), key=lambda r: -fl(r["gpu_ms_per_frame"]))[:5]
            rows.append((p["pass"], p["avg_ms_per_frame"], p.get("batch_ms_per_frame", ""), p.get("non_batch_ms_per_frame", ""),
                         "; ".join(f"{r['shader']} {r['gpu_ms_per_frame']}" for r in lst)))
        L.append(table(rows, ["pass", "ms/frame", "batch ms", "non-batch ms", "top shaders (ms/frame)"]))
        L.append("")

    L += memory_section(d)

    L.append("## Reading notes\n")
    L.append("* mode1 = honest speed; mode2 = per-shader breakdown with inflated absolute times. Shader percentages are of the mode 2 frame.\n"
             "* `non-batch ms` of a pass = pass time minus draw batches: fullscreen work, clears, GPU idle gaps and timestamp overhead.\n"
             "* GPU buckets are timestamp intervals since the previous mark and can include idle gaps; CPU scopes are inclusive.\n"
             "* Ranges are across the measured repeats of this session only. For decisions use `scripts/profile-ab.sh` (interleaved A/B).\n"
             "* `Memory` section (only with `profile.sh --mem`): analytic VRAM census + `/proc` RAM breakdown, from a separate pass.\n"
             "* Full column documentation: `profiling/README.md`. Inputs that produced this data: `environment/`.\n")
    (d / "summary.md").write_text("\n".join(L))
